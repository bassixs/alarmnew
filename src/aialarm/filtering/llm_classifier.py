"""LLM-классификатор релевантности (Вариант A из ТЗ)."""
from __future__ import annotations

from dataclasses import dataclass

from aialarm.config import get_settings
from aialarm.llm.client import get_llm_client

_SCHEMA = {
    "type": "object",
    "properties": {
        "relevant": {"type": "boolean"},
        "matched_thesis": {"type": "string"},
        "confidence": {"type": "integer", "minimum": 0, "maximum": 100},
        "reason": {"type": "string"},
    },
    "required": ["relevant", "matched_thesis", "confidence", "reason"],
}

_SYSTEM = """Ты — редактор регионального новостного канала.
Канал и аудитория: {tone}
Тезисы, под которые ДОЛЖНА подходить новость (иначе не публикуем):
{theses}

Твоя задача — решить, релевантна ли новость хотя бы одному тезису.
Отбирай материал как кандидат для редактора, а не как окончательное решение о публикации:
если локальная новость конкретно соответствует тезису и может быть полезна или интересна
жителям, помечай её relevant=true. Окончательное решение всё равно примет редактор.

Предпочтительные темы для Калуги и области:
- крупные ДТП, заметные криминальные истории и иные значимые происшествия;
- состояние и развитие городской инфраструктуры: дороги, транспорт, ЖКХ, благоустройство;
- общество, социальная сфера, экономика региона, предприятия, инвестиции, рабочие места;
- «удивительное рядом»: необычные местные факты, рекорды и события, способные искренне
  удивить читателя (например, гигантская тыква);
- нетипичные для региона события и городские новинки: необычные площадки, форматы досуга,
  визиты федерального уровня и другие поводы, о которых будут говорить;
- важные и знаковые для общества решения и результаты: новые машины скорой помощи,
  заметные проекты, достижения жителей, культура и спорт.
Официальные решения, планы, назначения и заявления властей также релевантны, если они
содержат конкретное изменение или пользу для жителей, а не только протокольную формальность.

СРОЧНЫЕ НОВОСТИ: ставь relevant=true и confidence 80–100, если событие развивается сейчас
или требует быстрого информирования жителей. Это резонансные пожары с пострадавшими,
пожары на производстве, взрывы, эвакуации, крупные аварии и ДТП с пострадавшими, погибшими,
перекрытием дорог, серьёзными пробками или большим числом машин. Срочной может быть и другая
ситуация с риском для людей, инфраструктуры или заметным влиянием на город.

Не требуй, чтобы каждая такая новость была «крупной»: для обычного, но полезного
локального повода ставь confidence 40–65. Высокую уверенность оставляй для действительно
значимых тем. Не понижай оценку только потому, что новость опубликована силовым ведомством:
чувствительность и последующую ручную модерацию определяет система отдельно.
Считай НЕРЕЛЕВАНТНЫМИ: рекламу и промо, гороскопы, розыгрыши и конкурсы репостов,
частные объявления, а также федеральные/иногородние новости без прямой связи с
Калужской областью.
НЕ БЕРИ: точечные отключения электричества или воды, мелкие ДТП без пострадавших и без
заметного влияния на движение, рядовые бытовые происшествия и мелкий криминал. Не выбирай
рисковые для репутации региональных властей темы: массовые заболевания школьников,
конфликты в школах, а также любые новости, связанные с мигрантами. Для этих тем всегда
relevant=false и низкая confidence, даже если они вызывают обсуждение.
confidence отражает и релевантность, и значимость новости для канала.
Отвечай КРАТКО: matched_thesis — короткое название темы (2-4 слова), НЕ переписывай тезис
целиком; reason — одно короткое предложение (до 15 слов).
Ответь строго по схеме инструмента."""


_DISTRICT_APPENDIX = """

Это отдельная лента для жителей {district_title}. Отбирай новости по следующим правилам.
БЕРИ:
- позитивные и действительно содержательные новости о районе: заметные изменения, новые
  объекты, благоустройство, полезные решения и события для жителей;
- оперативные достижения местных жителей, коллективов, школ, спортсменов, волонтёров и
  предприятий — если это не рядовое участие, а результат, победа или повод для гордости;
- красивые местные пейзажи, сезонные явления и природу, только если фото/факт сам по себе
  интересен аудитории, а не является обычным «добрым утром»;
- резонансные и срочные события района: важные происшествия, перекрытия, пожары, аварии,
  проблемы инфраструктуры — только при конкретных подтверждённых фактах;
- погоду, если это предупреждение, опасное явление или заметное изменение, влияющее на
  жителей; обычный ежедневный прогноз не бери;
- интересные местные факты, историю, необычных людей, рекорды и «удивительное рядом».

НЕ БЕРИ: поздравления без новости, мелкие отчёты учреждений, афиши без заметного повода,
рекламу, конкурсы/розыгрыши, обычные школьные занятия, дубли, федеральные и областные
новости без прямого отношения к району. Не додумывай резонанс и не выбирай неподтверждённые
слухи. Для чувствительных тем сохраняй фактический нейтральный подход: финальное решение
всё равно остаётся за модератором.
"""


@dataclass(slots=True)
class ClassifyResult:
    relevant: bool
    matched_thesis: str
    confidence: int
    reason: str


def classify(title: str, body: str, district_title: str = "") -> ClassifyResult:
    proj = get_settings().project
    theses = "\n".join(f"- {t}" for t in proj.theses)
    system = _SYSTEM.format(tone=proj.tone_of_voice or "региональные новости", theses=theses)
    if district_title:
        system += _DISTRICT_APPENDIX.format(district_title=district_title)
    user = f'Новость: "{title}. {(body or "")[:2000]}"'
    data = get_llm_client().structured(
        model=proj.llm.classify_model,
        system=system,
        user=user,
        schema=_SCHEMA,
        max_tokens=1000,  # minimax пишет многословно; тесно -> обрезка JSON
    )
    return ClassifyResult(
        relevant=bool(data.get("relevant")),
        matched_thesis=str(data.get("matched_thesis", "")),
        confidence=int(data.get("confidence", 0)),
        reason=str(data.get("reason", "")),
    )
